//! Embedded Tree-sitter query set for the native provider (`INFRA-008`).
//!
//! `scopemux-core` reads query files from `SCMU_QUERIES_DIR` at runtime, so a
//! portable binary cannot depend on the build machine's `OUT_DIR` or native
//! cache.

/// Resolve the on-disk Tree-sitter query directory for the native provider.
///
/// Native builds embed the query set and materialize it into the user cache on
/// first use; an explicit `SCMU_QUERIES_DIR` that points at a directory always
/// wins.
///
/// Returns `None` for non-native builds, check-only builds with no embedded
/// queries, or when materialization fails. Callers treat that as unavailable
/// and keep the generic provider.
pub fn ensure_queries_dir() -> Option<std::path::PathBuf> {
    #[cfg(feature = "native")]
    {
        native_queries::ensure()
    }
    #[cfg(not(feature = "native"))]
    {
        None
    }
}

#[cfg(feature = "native")]
mod native_queries {
    use std::path::{Path, PathBuf};
    use std::sync::OnceLock;

    // Generated by build.rs: `QUERIES: &[(&str, &[u8])]` with the query set
    // embedded via `include_bytes!`. No absolute build path is referenced.
    include!(concat!(env!("OUT_DIR"), "/scopemux_queries.rs"));

    pub(super) fn ensure() -> Option<PathBuf> {
        static DIR: OnceLock<Option<PathBuf>> = OnceLock::new();
        DIR.get_or_init(resolve).clone()
    }

    fn resolve() -> Option<PathBuf> {
        if let Some(dir) = std::env::var_os("SCMU_QUERIES_DIR") {
            let dir = PathBuf::from(dir);
            if dir.is_dir() {
                return Some(dir);
            }
            tracing::warn!(
                path = %dir.display(),
                "scopemux: SCMU_QUERIES_DIR is not a directory; using embedded queries"
            );
        }

        if QUERIES.is_empty() {
            tracing::warn!(
                "scopemux: this build has no embedded queries (SCOPEMUX_SKIP_NATIVE_BUILD)"
            );
            return None;
        }

        let cache_root = dirs::cache_dir()?;
        let base = cache_root.join("opencode").join("scopemux").join("queries");
        let target = base.join(env!("SCOPEMUX_QUERIES_KEY"));
        if !target.is_dir() {
            if let Err(error) = materialize(&target) {
                tracing::warn!(
                    error = %error,
                    path = %target.display(),
                    "scopemux: could not materialize embedded queries"
                );
                return None;
            }
        }
        std::env::set_var("SCMU_QUERIES_DIR", &target);
        Some(target)
    }

    /// Write the embedded query set atomically to `target`.
    fn materialize(target: &Path) -> std::io::Result<()> {
        let parent = target.parent().ok_or_else(|| {
            std::io::Error::other("scopemux query cache target has no parent directory")
        })?;
        std::fs::create_dir_all(parent)?;
        if target.is_dir() {
            return Ok(());
        }

        let temp = parent.join(format!(
            ".{}.tmp-{}",
            env!("SCOPEMUX_QUERIES_KEY"),
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&temp);

        let write_all = || -> std::io::Result<()> {
            for (relative, bytes) in QUERIES {
                let path = temp.join(relative);
                if let Some(directory) = path.parent() {
                    std::fs::create_dir_all(directory)?;
                }
                std::fs::write(&path, bytes)?;
            }
            Ok(())
        };
        if let Err(error) = write_all() {
            let _ = std::fs::remove_dir_all(&temp);
            return Err(error);
        }

        match std::fs::rename(&temp, target) {
            Ok(()) => Ok(()),
            // Another process won the race after our check.
            Err(_) if target.is_dir() => {
                let _ = std::fs::remove_dir_all(&temp);
                Ok(())
            }
            Err(error) => {
                let _ = std::fs::remove_dir_all(&temp);
                Err(error)
            }
        }
    }

    #[cfg(test)]
    pub(super) fn embedded_query_count() -> usize {
        QUERIES.len()
    }

    #[cfg(test)]
    pub(super) fn materialize_for_test(target: &Path) -> std::io::Result<()> {
        materialize(target)
    }
}

#[cfg(all(test, feature = "native"))]
mod tests {
    #[test]
    fn embedded_queries_are_present() {
        assert!(
            super::native_queries::embedded_query_count() > 0,
            "a native build must embed the scopemux-core query set"
        );
    }

    #[test]
    fn embedded_queries_materialize_idempotently() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("queries").join("test-key");

        super::native_queries::materialize_for_test(&target).unwrap();
        assert!(target.join("rust").join("docstrings.scm").is_file());
        assert!(target.join("c").join("docstrings.scm").is_file());

        // A second call must not fail or duplicate state.
        super::native_queries::materialize_for_test(&target).unwrap();
    }
}
